/*
在进行浮点数运算时，要时刻注意有效位数，并且有时候是不满足结合律的
（就是括号不能随便加，运算顺序会对结果产生影响）
事实上，对于会进行隐式转换的变量类型间的运算同样如此。
*/
#include<stdio.h>

int main(){
    /*例一：关于加法的小数位截断*/
    //1e10 默认是 double,需要加上 f 表示单精度浮点数
    //先计算 3.14f + 1e10f 会导致小数位存储位数不够而把 3.14 的二进制表示的相关位数截断，导致消失
    printf("%f\n", (3.14f + 1e10f) - 1e10f);//输出 ：0.000000
    printf("%f\n", 3.14f + (1e10f - 1e10f));//输出 ：3.140000
    //这两个输出结果不一样

    /*例二：关于乘法的无穷大溢出*/
    printf("%f\n", (1e20f * 1e20f) * 1e-20f);//输出 ：1.#INF00 （正无穷）
    printf("%f\n", 1e20 * (1e20 * 1e-20));//输出（这里没加 f 是 double类型 ：100000000000000000000.000000 (1e20)
    printf("%f\n", 1e20f * 1e20f - 1e20f * 1e20f);//输出 ：-1.#IND00 （符号位为负数的未定义数 NaN）
    return 0;
}