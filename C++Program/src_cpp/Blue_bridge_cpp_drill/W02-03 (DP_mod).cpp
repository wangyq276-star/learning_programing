/*
描述
打表法是用空间换时间的好办法，对于庞大的敌人，采用查表的方法才能迅速置地人于死地。
林克的任务，使用打表法解决如下问题：
Pell数列a1, a2, a3, ...的定义是这样的:
a1= 1, a2= 2, ... , an= 2 * a(n − 1)+ a(n - 2) (n > 2)。
给出一个正整数k，要求Pell数列的第k项模上32767是多少。
(注：32767的二进制表示是 0111 1111 1111 1111)

输入
第1行是测试数据的组数n，后面跟着n行输入。
每组测试数据占1行，包括一个正整数k (1 ≤ k < 1000000)。

输出
n行，每行输出对应一个输入。输出应是一个非负整数。
*/
#include <iostream>
using namespace std;

const int N = 1e6 + 10;
const int p = 32767;
int a[N] = {0, 1, 2};
//此处加入 mk 来记录已经计算过的最大项数
int K = 0, mk = 2;

int mod32767(int k){
    //如果 k 小于已经计算过的最大项数，那么直接查表无需再次计算
    if (k == 1 || k == 2 || k <= mk){
        return a[k];
    }

    /* 
        这是常见的作法，也是具有一般性的做法
        但本题由于 32767 = 2^15 - 1 
        因此 x(二进制) %  ≡ （高15位 × 32767 + 低15位）% 32767 
                        = （高15位 + 低15位）% 32767
        （现代编译器（GCC、Clang）本来就会把 x % 32767 优化成乘法 + 移位
        跟手写位运算生成的指令差不多甚至更好。）
    for (int i = mk + 1; i < k + 1; i++){
        a[i] = ((2 * a[i - 1]) % p + a[i - 2]) % p;
    }
    */
    //以下为根据这一性质编写的代码
    for (int i = mk; i < k + 1; i++){
        int x = 2 * a[i - 1] + a[i - 2];
        //使用 x & 32767 取后15位，使用 x >> 15 取前15位
        x = (x & 32767) + (x >> 15);
        if (x >= 32767) x -= 32767;
        a[i] = x;
    }

    mk = k;
    return a[k];
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n;
    cin >> n;
    while (n--){
        cin >> K;
        cout << mod32767(K) << endl;
    }
    return 0;
}